#!/usr/bin/env bash
# Compiles SessionInstaller.java to a DEX and writes docs/car-setup.sh with the DEX base64-embedded.
# Run after changing SessionInstaller.java. Needs JDK and an Android SDK (android.jar + d8).
#   SDK:  $ANDROID_HOME or $ANDROID_SDK_ROOT, else the default Windows/Linux locations.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
docs="$(dirname "$here")"

sdk="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
[ -n "$sdk" ] || for c in "$LOCALAPPDATA/Android/Sdk" "$HOME/AppData/Local/Android/Sdk" "$HOME/Android/Sdk" "$HOME/Library/Android/sdk"; do
  [ -d "$c" ] && { sdk="$c"; break; }
done
[ -d "$sdk" ] || { echo "Android SDK not found; set ANDROID_HOME" >&2; exit 1; }

android_jar="$(ls "$sdk"/platforms/android-*/android.jar | sort -V | tail -n1)"
build_tools="$(ls -d "$sdk"/build-tools/* | sort -V | tail -n1)"
d8="$build_tools/d8"; [ -x "$d8" ] || d8="$build_tools/d8.bat"

work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT
javac -source 8 -target 8 -bootclasspath "$android_jar" -d "$work" "$here/SessionInstaller.java"
"$d8" --min-api 30 --output "$work" "$work"/qssop/*.class
b64="$(base64 -w0 "$work/classes.dex" 2>/dev/null || base64 "$work/classes.dex" | tr -d '\n')"

out="$docs/car-setup.sh"
{
cat <<'HEAD'
#!/system/bin/sh
# GENERATED by docs/installer/build-installer.sh -- edit SessionInstaller.java, not this file.
# Runs on the head unit as `sh /data/local/tmp/qs_r.sh`, pushed by the setup page next to the APK.
# The car (Desay SV, SOP6) refuses `pm install` from the adb-shell uid, so we install through a
# PackageInstaller session opened by an embedded DEX run with app_process -- the route that passes
# the car's install gate. The word "install" never reaches an adb command line (adbd drops those).
# All pushed/temporary files are deleted however this ends.
PKG=com.carlosrpg.cherry.quicksettings
APK=/data/local/tmp/qs.apk
DEX=/data/local/tmp/qs_s.dex
trap 'rm -f /data/local/tmp/qs.apk /data/local/tmp/qs_r.sh "$DEX"' 0

[ -f "$APK" ] || { echo "QS_RESULT:missing"; exit 1; }

base64 -d > "$DEX" <<'QS_DEX_B64'
HEAD
echo "$b64"
cat <<'TAIL'
QS_DEX_B64
chmod 644 "$DEX"

OUT=$(CLASSPATH="$DEX" app_process /system/bin qssop.SessionInstaller "$APK" 2>&1)
echo "$OUT"
case "$OUT" in
  *QS_INSTALL:ok*)
    echo "QS_RESULT:ok"
    monkey -p "$PKG" -c android.intent.category.LAUNCHER 1 >/dev/null 2>&1
    ;;
  *)
    # Session install refused: leave the APK in Download for a file-manager install.
    if cp "$APK" /sdcard/Download/QuickSettings.apk; then echo "QS_RESULT:copied"; else echo "QS_RESULT:failed"; fi
    exit 1
    ;;
esac
TAIL
} > "$out"

echo "Wrote $out ($(wc -c < "$out") bytes, DEX $(wc -c <<<"$b64") b64 chars)"
